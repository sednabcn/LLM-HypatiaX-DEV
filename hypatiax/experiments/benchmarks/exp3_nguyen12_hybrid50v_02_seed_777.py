    def _detect_rational_pattern(self, X: np.ndarray, y: np.ndarray) -> bool:
        if X.shape[1] < 1 or np.any(y <= 0):
            return False
        try:
            inv_y = 1.0 / y
            for i in range(X.shape[1]):
                xi = X[:, i]
                if np.any(xi <= 0):
                    continue
                inv_x = 1.0 / xi
                r2 = r2_score(inv_y, LinearRegression().fit(inv_x.reshape(-1,1), inv_y).predict(inv_x.reshape(-1,1)))
                if r2 > 0.85:
                    return True
            # Saturation shape: monotone increasing + plateau (Michaelis-Menten, Hill)
            for i in range(X.shape[1]):
                xi = X[:, i]
                sort_idx = np.argsort(xi)
                y_sorted = y[sort_idx]
                if y_sorted[-1] > y_sorted[0]:
                    diffs = np.diff(y_sorted)
                    if np.all(diffs >= -1e-6) and diffs[-1] < diffs[0] * 0.3:
                        return True
        except Exception:
            pass
        return False

