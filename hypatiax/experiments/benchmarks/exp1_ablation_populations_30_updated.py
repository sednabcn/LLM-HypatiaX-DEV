"""## 3 · `run_condition` — single equation × single condition"""

def run_condition(eq, condition, seed=42, niterations=NITERATIONS,
                  timeout_secs=TIMEOUT_SECS, populations=POPULATIONS,
                  wall_clock_limit=EQUATION_WALL_CLOCK_TIMEOUT):
    """Run one equation under 'pysr_only' or 'hypatia'.

    hypatia  -> HybridDiscoverySystem v5.1 (hybrid_system_v50_2):
                FIX-A (RMSE from expression), FIX-B (key aliases),
                FIX-C (deterministic PySR), FIX-D (extreme-scale log),
                FIX-POW (auto pow for non-negative X), DiscoveryConfig
                auto-config and operator injection are all active.
    pysr_only -> raw PySRRegressor (clean baseline, unchanged).
    """
    eq_seed = seed + EQ_ID.get(eq["name"], 0) * 7
    dbg(f"run_condition: {eq['name']} [{condition}] seed={eq_seed}")

    X_train, X_test, y_train, y_test, X_all, y_all = generate_data(
        eq, N=200, noise_level=0.05, seed=eq_seed)
    extrap_sets = {}
    for regime_name, _ in EXTRAP_REGIMES:
        X_e, y_e = generate_extrap_data(eq, regime=regime_name, N=100, seed=eq_seed)
        extrap_sets[regime_name] = (X_e, y_e)

    sanitizer = VariableNameSanitizer()
    safe_var_names, had_conflict = sanitizer.sanitize(eq["vars"])

    # ── hypatia: route through HybridDiscoverySystem v5.1 ────────────────────
    if condition == "hypatia":
        if HybridDiscoverySystem is None:
            raise RuntimeError("HybridDiscoverySystem not imported — check hybrid_system_v50_2.py path")

        _api_key = os.environ.get("ANTHROPIC_API_KEY", "")
        _use_llm = bool(_api_key.startswith("sk-"))

        _domain_slug = eq["domain"].lower().replace(" ", "_")

        hybrid = HybridDiscoverySystem(
            domain=_domain_slug,
            discovery_config=DiscoveryConfig(
                niterations=niterations,
                enable_auto_configuration=True,
                # Pass timeout to engine so it respects the same limit
                pysr_timeout=timeout_secs,
            ),
            max_retries=3,
            use_llm=_use_llm,
            llm_mode="hybrid" if _use_llm else "none",
            llm_n_candidates=3,
            llm_temperature=0.3,
            enable_physics_fallback=False,
            allow_nondeterministic=False,   # FIX-C
        )

        t0 = time.time()
        try:
            with _Timeout(wall_clock_limit):
                res = hybrid.discover(
                    X_train, y_train,
                    var_names=safe_var_names,
                    description=eq["name"],
                    metadata={
                        "equation_name": eq["name"],
                        "variable_descriptions": {v: v for v in eq["vars"]},
                        "variable_units": {v: "" for v in eq["vars"]},
                        "noise_level": 0.05,
                        "domain": _domain_slug,
                        # FIX-D + FIX-POW run automatically inside discover()
                    },
                )
            sr_time = time.time() - t0
        except TimeoutError:
            sr_time = time.time() - t0
            print(f"  [hypatia] TIMEOUT after {sr_time:.1f}s")
            return {
                "condition": condition, "success": False, "timed_out": True,
                "excluded_from_timing": True,
                "train_r2": None, "train_rmse": None,
                "extrap_r2_near": None, "extrap_r2_medium": None, "extrap_r2_far": None,
                "extrap_rmse_near": None, "extrap_rmse_medium": None, "extrap_rmse_far": None,
                "sr_time_s": sr_time, "llm_time_s": 0.0, "total_time_s": sr_time,
                "best_expression": "TIMED_OUT", "complexity": None,
                "llm_expression": None, "llm_confidence": None,
                "engine_version": "5.1",
            }
        except Exception as e:
            print(f"  [hypatia] ERROR: {e}")
            import traceback; traceback.print_exc()
            return {
                "condition": condition, "success": False, "timed_out": False,
                "excluded_from_timing": False, "error": str(e),
                "train_r2": None, "train_rmse": None,
                "extrap_r2_near": None, "extrap_r2_medium": None, "extrap_r2_far": None,
                "extrap_rmse_near": None, "extrap_rmse_medium": None, "extrap_rmse_far": None,
                "sr_time_s": time.time() - t0, "llm_time_s": 0.0,
                "total_time_s": time.time() - t0,
                "best_expression": "ERROR", "complexity": None,
                "llm_expression": None, "llm_confidence": None,
                "engine_version": "5.1",
            }

        # FIX-B: res has "formula", "expression", "final_formula", "r2", "rmse"
        best_expr_raw = sanitizer.restore(res.get("formula", "N/A"))
        train_r2   = res.get("r2", None)
        train_rmse = res.get("rmse", float("inf"))   # FIX-A: original-unit RMSE
        scale_log  = res.get("scale_log", False)      # FIX-D flag
        complexity = len(best_expr_raw) if best_expr_raw not in ("N/A", "") else None

        # Extrapolation: eval expression directly (FIX-D: apply log-scale to
        # extrap X if discover() did so for training data)
        extrap_r2, extrap_rmse = {}, {}
        _norm_expr = best_expr_raw.replace("^", "**")
        for regime_name, (X_e, y_e) in extrap_sets.items():
            try:
                _X_e_use = X_e.copy().astype(float)
                if scale_log:
                    for _ci, _vn in enumerate(safe_var_names):
                        _col = X_e[:, _ci]
                        _abs = np.abs(_col[np.isfinite(_col) & (_col != 0)])
                        if len(_abs) >= 2:
                            _rng = np.log10(_abs.max() + 1e-30) - np.log10(_abs.min() + 1e-30)
                            if _rng > 6:
                                _X_e_use[:, _ci] = np.sign(_col) * np.log10(np.abs(_col) + 1.0)
                _math_ns = {
                    "sqrt": np.sqrt, "exp": np.exp, "log": np.log,
                    "sin":  np.sin,  "cos": np.cos, "tan": np.tan,
                    "abs":  np.abs,  "log2": np.log2, "log10": np.log10,
                    "pow":  np.power, "sign": np.sign,
                }
                _ns = {"np": np, **_math_ns,
                       **{vn: _X_e_use[:, ci]
                          for ci, vn in enumerate(safe_var_names)}}
                _y_pred = eval(_norm_expr, {"__builtins__": {}}, _ns)
                _y_pred = np.asarray(_y_pred, dtype=float)
                if _y_pred.shape == ():
                    _y_pred = np.full(len(y_e), float(_y_pred))
                extrap_r2[regime_name]   = _safe_r2(y_e, _y_pred)
                extrap_rmse[regime_name] = _safe_rmse(y_e, _y_pred)
            except Exception as _ee:
                dbg(f"extrap eval failed ({regime_name}): {_ee}")
                extrap_r2[regime_name]   = None
                extrap_rmse[regime_name] = None

        def _f(v):
            if v is None: return "N/A"
            try: return f"{float(v):.4f}" if np.isfinite(float(v)) else "N/A"
            except: return "N/A"
        print(f"  [hypatia] {best_expr_raw[:55]}  R2={_f(train_r2)}  "
              f"extrap(near={_f(extrap_r2.get('near'))} "
              f"med={_f(extrap_r2.get('medium'))} "
              f"far={_f(extrap_r2.get('far'))})  {sr_time:.1f}s  "
              f"scale_log={scale_log}  llm={res.get('llm_mode','none')}")

        return {
            "condition": condition, "success": res.get("success", False),
            "timed_out": False, "excluded_from_timing": False,
            "train_r2": train_r2, "train_rmse": train_rmse,
            "extrap_r2_near":    extrap_r2.get("near"),
            "extrap_r2_medium":  extrap_r2.get("medium"),
            "extrap_r2_far":     extrap_r2.get("far"),
            "extrap_rmse_near":  extrap_rmse.get("near"),
            "extrap_rmse_medium":extrap_rmse.get("medium"),
            "extrap_rmse_far":   extrap_rmse.get("far"),
            "sr_time_s": sr_time, "llm_time_s": 0.0, "total_time_s": sr_time,
            "best_expression": best_expr_raw, "complexity": complexity,
            "llm_expression": None, "llm_confidence": None,
            # v5.1 provenance extras
            "engine_version": "5.1",
            "scale_log": scale_log,
            "rmse_original_units": train_rmse,
            "llm_mode_used": res.get("llm_mode", "none"),
            "validation_score": res.get("validation_score", None),
        }

    # ── pysr_only: raw PySRRegressor (clean baseline, unchanged) ─────────────
    llm_expression = None
    llm_confidence = 0.0
    llm_time       = 0.0

    model = make_pysr(
        warm_start_expr=None,
        seed=eq_seed, niterations=niterations,
        timeout_secs=timeout_secs, populations=populations,
    )

    t_sr = time.time()
    try:
        with _Timeout(wall_clock_limit):
            model.fit(X_train, y_train, variable_names=safe_var_names)
        sr_time = time.time() - t_sr
    except TimeoutError as te:
        sr_time = time.time() - t_sr
        print(f"  [{condition}] TIMEOUT after {sr_time:.1f}s")
        return {
            "condition": condition, "success": False, "timed_out": True,
            "excluded_from_timing": True,
            "train_r2": None, "train_rmse": None,
            "extrap_r2_near": None, "extrap_r2_medium": None, "extrap_r2_far": None,
            "extrap_rmse_near": None, "extrap_rmse_medium": None, "extrap_rmse_far": None,
            "sr_time_s": sr_time, "llm_time_s": llm_time, "total_time_s": sr_time + llm_time,
            "best_expression": "TIMED_OUT", "complexity": None,
            "llm_expression": llm_expression, "llm_confidence": llm_confidence,
        }
    except Exception as e:
        print(f"  [{condition}] ERROR: {e}")
        return {
            "condition": condition, "success": False, "timed_out": False,
            "excluded_from_timing": False, "error": str(e),
            "train_r2": None, "train_rmse": None,
            "extrap_r2_near": None, "extrap_r2_medium": None, "extrap_r2_far": None,
            "extrap_rmse_near": None, "extrap_rmse_medium": None, "extrap_rmse_far": None,
            "sr_time_s": time.time() - t_sr, "llm_time_s": llm_time,
            "total_time_s": time.time() - t_sr + llm_time,
            "best_expression": "ERROR", "complexity": None,
            "llm_expression": llm_expression, "llm_confidence": llm_confidence,
        }

    try:
        y_pred_train = model.predict(X_train)
        train_r2   = _safe_r2(y_train, y_pred_train)
        train_rmse = _safe_rmse(y_train, y_pred_train)

        extrap_r2, extrap_rmse = {}, {}
        for regime_name, (X_e, y_e) in extrap_sets.items():
            y_pred_e = model.predict(X_e)
            extrap_r2[regime_name]   = _safe_r2(y_e, y_pred_e)
            extrap_rmse[regime_name] = _safe_rmse(y_e, y_pred_e)

        best_expr_raw = str(model.sympy())
        best_expr     = sanitizer.restore(best_expr_raw)
        try:
            best_row   = model.get_best()
            complexity = int(best_row["complexity"])
        except Exception:
            eqs_df     = model.equations_
            complexity = int(eqs_df.loc[eqs_df["loss"].idxmin(), "complexity"])
    except Exception as e:
        import traceback; traceback.print_exc()
        train_r2 = train_rmse = None
        extrap_r2   = {r: None for r, _ in EXTRAP_REGIMES}
        extrap_rmse = {r: None for r, _ in EXTRAP_REGIMES}
        best_expr = "evaluation_error"; complexity = None

    total_time = sr_time + llm_time
    def _f(v): return f"{v:.4f}" if v is not None and np.isfinite(v) else "N/A"
    print(f"  [{condition}] train_R2={_f(train_r2)}  "
          f"extrap(near={_f(extrap_r2.get('near'))} "
          f"med={_f(extrap_r2.get('medium'))} "
          f"far={_f(extrap_r2.get('far'))})  time={total_time:.1f}s")
    return {
        "condition": condition, "success": True,
        "timed_out": False, "excluded_from_timing": False,
        "train_r2": train_r2, "train_rmse": train_rmse,
        "extrap_r2_near":    extrap_r2.get("near"),
        "extrap_r2_medium":  extrap_r2.get("medium"),
        "extrap_r2_far":     extrap_r2.get("far"),
        "extrap_rmse_near":  extrap_rmse.get("near"),
        "extrap_rmse_medium":extrap_rmse.get("medium"),
        "extrap_rmse_far":   extrap_rmse.get("far"),
        "sr_time_s": sr_time, "llm_time_s": llm_time, "total_time_s": total_time,
        "best_expression": best_expr, "complexity": complexity,
        "llm_expression": llm_expression, "llm_confidence": llm_confidence,
    }

