def get_llm_proposal(eq):
    if not ANTHROPIC_AVAILABLE:
        return None, 0.0, 0.0
    client = _get_anthropic_client()
    var_desc = ", ".join(f"{v} (range: {r[0]:.3g}–{r[1]:.3g})"
                         for v, r in zip(eq["vars"], eq["train_range"]))
    prompt = (f"You are a mathematical physicist inferring equations from data.\n"
              f"Domain: {eq['domain']}\nEquation name: {eq['name']}\n"
              f"Variables: {var_desc}\n\n"
              "Generate ONE candidate analytical expression.\n"
              'Respond ONLY with JSON: {"expression": "...", "confidence": 0.0–1.0, "latex": "..."}')
    t0 = time.time()
    try:
        resp = client.messages.create(
            model=MODEL_STRING, max_tokens=256,
            messages=[{"role": "user", "content": prompt}],
        )
        elapsed = time.time() - t0
        raw = resp.content[0].text.strip()
        raw = re.sub(r"```(?:json)?", "", raw).strip().rstrip("`")
        data = json.loads(raw)
        return data.get("expression"), float(data.get("confidence", 0.5)), elapsed
    except Exception as e:
        dbg(f"LLM proposal failed: {e}")
        return None, 0.0, time.time() - t0

# ── Timeout context manager (SIGALRM, Unix only) ──────────────────────────────
class _Timeout:
    def __init__(self, seconds):
        self.seconds = int(seconds)
        self._ok = hasattr(signal, "SIGALRM")
    def _handler(self, signum, frame):
        raise TimeoutError(f"PySR exceeded {self.seconds}s wall-clock limit")
    def __enter__(self):
        if self._ok and self.seconds > 0:
            signal.signal(signal.SIGALRM, self._handler)
            signal.alarm(self.seconds)
        return self
    def __exit__(self, *args):
        if self._ok: signal.alarm(0)

