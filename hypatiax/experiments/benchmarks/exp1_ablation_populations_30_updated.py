# ── Variable name sanitiser ───────────────────────────────────────────────────
class VariableNameSanitizer:
    RESERVED = {"S", "N", "C", "D", "E", "I", "O"}
    def __init__(self):
        self.fwd, self.rev = {}, {}
    def sanitize(self, names):
        out, conflict = [], False
        for v in names:
            if v in self.RESERVED:
                safe = f"var_{v}"
                c = 1
                while safe in out or safe in names:
                    safe = f"var_{v}{c}"; c += 1
                self.fwd[v] = safe; self.rev[safe] = v
                out.append(safe); conflict = True
            else:
                out.append(v)
        return out, conflict
    def restore(self, expr):
        for orig, safe in self.fwd.items():
            expr = re.sub(r"\b" + re.escape(safe) + r"\b", orig, expr)
        return expr
    def log(self):
        return str(self.fwd)

# ── Data generation ───────────────────────────────────────────────────────────
def generate_data(eq, N=200, noise_level=0.05, seed=42):
    rng = np.random.RandomState(seed)
    n_vars = len(eq["vars"])
    X = np.column_stack([rng.uniform(lo, hi, N) for lo, hi in eq["train_range"]])
    y = eq["fn"](*[X[:, i] for i in range(n_vars)])
    noise_std = noise_level * np.std(y)
    y_noisy = y + rng.normal(0, noise_std, N)
    X_train, X_test, y_train, y_test = train_test_split(X, y_noisy, test_size=0.2, random_state=seed)
    return X_train, X_test, y_train, y_test, X, y

def generate_extrap_data(eq, regime="medium", N=100, seed=42):
    rng = np.random.RandomState(seed + 999)
    n_vars = len(eq["vars"])
    if regime == "medium":
        ranges = eq["extrap_range"]
    else:
        mult = {"near": (1.0, 1.5), "far": (4.0, 6.0)}[regime]
        ranges = [(hi * mult[0], hi * mult[1]) for (_, hi) in eq["train_range"]]
    X = np.column_stack([rng.uniform(lo, hi, N) for lo, hi in ranges])
    y = eq["fn"](*[X[:, i] for i in range(n_vars)])
    return X, y

# ── Metrics ───────────────────────────────────────────────────────────────────
def _safe_r2(y_true, y_pred):
    if not np.all(np.isfinite(y_pred)): return float("-inf")
    if len(y_true) < 2: return float("nan")
    ss_res = np.sum((y_true - y_pred)**2)
    ss_tot = np.sum((y_true - np.mean(y_true))**2)
    if ss_tot < 1e-10: return 1.0 if ss_res < 1e-10 else float("-inf")
    return float(1 - ss_res / ss_tot)

def _safe_rmse(y_true, y_pred):
    if not np.all(np.isfinite(y_pred)) or len(y_true) == 0: return float("inf")
    return float(np.sqrt(np.mean((y_true - y_pred)**2)))

