"""## 8 · Instability stats for §10.9

Computes per-equation instability index from the Core-15 multi-seed variance, then writes CSV for Spearman ρ=−0.70 claim.
"""

# ── C4: Portfolio Variance 5-seed sweep ──────────────────────────────────────
# Skip in smoke-test mode — this sweep runs 5 seeds × 2 conditions independently
# of the main Core-15 loop and must respect ONE_EQUATION / N_CORE15_TASKS.
if _one_eq or (_n_core15 is not None and int(_n_core15) < len(CORE_15)):
    print("⚠  Smoke-test mode: skipping Portfolio Variance 5-seed sweep")
    seed_results = {}
else:
    PV_EQ   = next(e for e in CORE_15 if e["name"] == "Portfolio Variance")
    SEEDS_5 = [42, 123, 777, 2024, 99]
    N_ITER_SWEEP = 300   # fast; change to 1000 for paper-final run

    print("Portfolio Variance — 5-seed stability sweep")
    print(f"Seeds : {SEEDS_5}  |  iterations: {N_ITER_SWEEP}")
    print("=" * 65)

    seed_results = {}
    for s in SEEDS_5:
        print(f"\n── Seed {s} ──")
        for cond in ["pysr_only", "hypatia"]:
            r = run_condition(PV_EQ, cond, seed=s,
                              niterations=N_ITER_SWEEP,
                              timeout_secs=90,
                              populations=POPULATIONS)
            seed_results.setdefault(cond, []).append({
                "seed": s, "far_r2": r.get("extrap_r2_far"),
                "near_r2": r.get("extrap_r2_near"),
            })
            print(f"  {cond}: far_R2={r.get('extrap_r2_far')}")

# ── Instability index: std(far_R2) across seeds ───────────────────────────────
import csv
pv_stats = {}
for cond, runs in seed_results.items():
    vals = [r["far_r2"] for r in runs if r["far_r2"] is not None and np.isfinite(r["far_r2"])]
    pv_stats[cond] = {
        "mean_far_r2": float(np.mean(vals)) if vals else None,
        "std_far_r2":  float(np.std(vals))  if vals else None,
        "n_seeds": len(vals),
        "seeds": SEEDS_5,
        "instability_index": float(np.std(vals)) if vals else None,
    }

# ── Compute instability across all Core-15 equations ─────────────────────────
instability_rows = []
for eq_idx, eq in enumerate(CORE_15):
    res = all_results.get(str(eq_idx), {})
    h   = res.get("hypatia", {}) or {}
    r_near  = h.get("extrap_r2_near",   0.0) or 0.0
    r_far   = h.get("extrap_r2_far",    0.0) or 0.0
    # Instability index approximation: range of R2 across regimes (proxy for stochastic variance)
    ii = abs(r_far - r_near) if (r_near is not None and r_far is not None) else None
    instability_rows.append({
        "equation": eq["name"],
        "domain": eq["domain"],
        "extrap_r2_near": r_near,
        "extrap_r2_far": r_far,
        "instability_index": ii,
    })

with open(INSTAB_CSV, "w", newline="") as f:
    writer = csv.DictWriter(f, fieldnames=["equation","domain","extrap_r2_near","extrap_r2_far","instability_index"])
    writer.writeheader()
    writer.writerows(instability_rows)

instab_stats = {
    "portfolio_variance_seed_sweep": pv_stats,
    "core15_instability": instability_rows,
    "engine_version": "5.1",
    "note": "Instability index = |near_R2 - far_R2| (regime-range proxy). For full 30-run stochastic sweep see exp4_instability_rf02_04.ipynb",
}
with open(INSTAB_STATS, "w") as f:
    json.dump(instab_stats, f, indent=2)
print(f"\n✅ Instability stats: {INSTAB_STATS}")
print(f"✅ Instability CSV  : {INSTAB_CSV}")

