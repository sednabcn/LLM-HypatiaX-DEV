def get_llm_proposal(eq):
    dbg(f"get_llm_proposal: {eq['name']}")
    if not ANTHROPIC_AVAILABLE:
        dbg("Anthropic not available — skipping LLM proposal")
        return None, 0.0, 0.0

    client = _get_anthropic_client()

    var_descriptions = ", ".join([
        f"{v} (range: {r[0]:.3g}–{r[1]:.3g})"
        for v, r in zip(eq["vars"], eq["train_range"])
    ])

    prompt = f"""You are a mathematical physicist inferring equations from data.

Domain: {eq['domain']}
Equation name: {eq['name']}
Variables: {var_descriptions}

Generate ONE candidate analytical expression for this relationship.
Respond ONLY with a JSON object with keys:
  "expression": the formula as a Python expression (use variable names exactly as given)
  "confidence": float 0-1
  "latex": LaTeX representation
  "interpretation": one sentence physical interpretation

Use only: +, -, *, /, **, np.exp(), np.log(), np.sin(), np.cos(), np.sqrt()
The expression must be evaluable with numpy."""

    t0 = time.time()
    for attempt in range(4):
        try:
            dbg(f"LLM API call attempt {attempt+1}/4 …")
            response = client.messages.create(
                model="claude-sonnet-4-20250514",
                max_tokens=1024,
                temperature=0.0,
                messages=[{"role": "user", "content": prompt}]
            )
            elapsed = time.time() - t0
            text = response.content[0].text.strip()
            dbg(f"LLM responded in {elapsed:.1f}s: {text[:120]}")
            json_match = re.search(r'\{.*\}', text, re.DOTALL)
            if json_match:
                data = json.loads(json_match.group())
                return data.get("expression"), data.get("confidence", 0.5), elapsed
        except Exception as e:
            if "529" in str(e) or "overloaded" in str(e).lower():
                wait = 15 * (attempt + 1)
                dbg(f"LLM overloaded (attempt {attempt+1}/4), retrying in {wait}s…")
                time.sleep(wait)
            else:
                dbg(f"LLM error: {e}")
                break

    return None, 0.0, time.time() - t0


