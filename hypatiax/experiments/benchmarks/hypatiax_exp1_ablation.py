class _Timeout:
    """Context manager: raises TimeoutError after `seconds` on Unix."""
    def __init__(self, seconds):
        self.seconds = int(seconds)
        self._supported = hasattr(signal, "SIGALRM")

    def _handler(self, signum, frame):
        raise TimeoutError(f"PySR fit exceeded {self.seconds}s wall-clock limit")

    def __enter__(self):
        if self._supported and self.seconds > 0:
            signal.signal(signal.SIGALRM, self._handler)
            signal.alarm(self.seconds)
        return self

    def __exit__(self, *args):
        if self._supported:
            signal.alarm(0)   # cancel any pending alarm


