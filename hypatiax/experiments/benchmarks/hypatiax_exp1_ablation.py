def evaluate_formula_ood(eq, X_ood, eval_mode_override=None):
    """
    Returns (y_true_ood, eval_mode) where eval_mode is 'sympy' or 'precomputed'.
    X_ood: shape (N, n_vars) — already generated OOD points.
    """
    formula = eq.get("formula_sympy")
    if formula and SYMPY_AVAILABLE and eval_mode_override != "precomputed":
        try:
            n_vars = len(eq["vars"])
            var_vals = {eq["vars"][i]: X_ood[:, i] for i in range(n_vars)}
            y_true = eval(formula, {"np": np, **var_vals})
            if np.all(np.isfinite(y_true)):
                return y_true, "sympy"
        except Exception as e:
            dbg(f"  evaluate_formula_ood sympy failed for {eq['name']}: {e} — falling back")
    # Fallback: regenerate via eq["fn"] (same as existing generate_extrap_data)
    n_vars = len(eq["vars"])
    y_true = eq["fn"](*[X_ood[:, i] for i in range(n_vars)])
    return y_true, "precomputed"


def compute_ood_r2_true(eq, model, regime, seed=42):
    """
    Generate OOD points, evaluate true formula (Mode A), predict with model.
    Returns (r2, eval_mode).
    """
    X_e, _ = generate_extrap_data(eq, regime=regime, N=200, seed=seed)
    y_true, eval_mode = evaluate_formula_ood(eq, X_e)
    y_pred = model.predict(X_e)
    return _safe_r2(y_true, y_pred), eval_mode


