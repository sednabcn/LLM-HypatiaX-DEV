def run_condition(eq, condition, seed=42, niterations=1000, timeout_secs=None, populations=30,
                  wall_clock_limit=None):
    """
    condition: 'pysr_only' or 'hypatia'
    wall_clock_limit: SIGALRM-based hard cap on model.fit() (main thread, Unix only).
    """
    dbg(f"run_condition START: {eq['name']} [{condition}]")
    eq_seed = seed + _CORE15_INDEX.get(eq["name"], CORE_15.index(eq)) * 7

    # ── Data ──────────────────────────────────────────────────────────────────
    dbg("Generating training data …")
    X_train, X_test, y_train, y_test, X_all, y_all = generate_data(
        eq, N=200, noise_level=0.05, seed=eq_seed
    )

    extrap_sets = {}
    for regime_name, _ in EXTRAP_REGIMES:
        X_e, y_e = generate_extrap_data(eq, regime=regime_name, N=100, seed=eq_seed)
        extrap_sets[regime_name] = (X_e, y_e)

    # ── Variable sanitisation ─────────────────────────────────────────────────
    sanitizer = VariableNameSanitizer()
    safe_var_names, had_conflict = sanitizer.sanitize(eq["vars"])
    if had_conflict:
        dbg(f"Variable sanitisation: {sanitizer.log()}")

    llm_expression = None
    llm_confidence = 0.0
    llm_time = 0.0

    # ── LLM proposal (hypatia only) ───────────────────────────────────────────
    if condition == "hypatia":
        dbg("Requesting LLM proposal …")
        llm_expression, llm_confidence, llm_time = get_llm_proposal(eq)
        if llm_expression:
            if had_conflict:
                for orig, safe in sanitizer.fwd.items():
                    llm_expression = re.sub(r"\b" + re.escape(orig) + r"\b", safe, llm_expression)
            dbg(f"LLM proposed: {llm_expression[:80]} (conf={llm_confidence:.2f})")
            print(f"  [{condition}] LLM proposed: {llm_expression[:80]} (conf={llm_confidence:.2f})")
        else:
            dbg("LLM proposal failed — falling back to PySR alone")
            print(f"  [{condition}] LLM proposal failed — falling back to PySR alone")

    # ── PySR fit (MAIN THREAD — no daemon thread) ─────────────────────────────
    if wall_clock_limit is None:
        wall_clock_limit = EQUATION_WALL_CLOCK_TIMEOUT

    dbg(f"Building PySRRegressor (wall-clock cap: {wall_clock_limit}s via SIGALRM) …")
    print(f"  [{condition}] Running PySR (wall-clock cap: {wall_clock_limit}s)…")

    model = make_pysr(
        warm_start_expr=llm_expression if condition == "hypatia" else None,
        seed=eq_seed,
        niterations=niterations,
        timeout_secs=timeout_secs,
        populations=populations,
    )

    dbg("Calling model.fit() on main thread …")
    t_sr_start = time.time()
