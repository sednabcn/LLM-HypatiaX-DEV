def make_pysr(seed=42, niterations=1000, timeout_secs=1100, populations=30):
    """
    PySRRegressor with parallelism='multithreading'.
    Safe on Colab: avoids Julia Distributed deadlock.
    Requires JULIA_NUM_THREADS set in Cell 1 before import pysr.
    """
    if not PYSR_AVAILABLE:
        raise RuntimeError('PySR not installed')
    global _PYSR_VALID_PARAMS
    if _PYSR_VALID_PARAMS is None:
        _PYSR_VALID_PARAMS = set(inspect.signature(PySRRegressor.__init__).parameters.keys())
    valid = _PYSR_VALID_PARAMS
    kwargs = dict(
        niterations=niterations,
        populations=populations,
        population_size=_r('pysr', 'population_size'),
        maxsize=_r('pysr', 'maxsize'),
        parsimony=_r('pysr', 'parsimony'),
        binary_operators=_r('pysr', 'binary_operators'),
        unary_operators=_r('pysr', 'unary_operators'),
        random_state=seed, verbosity=0, progress=False,
    )
    # multithreading: safe on Colab, ~N x faster than serial (N = CPU cores)
    if 'parallelism' in valid:
        kwargs['parallelism'] = 'multithreading'
    else:
        kwargs['procs'] = 0
        kwargs['multithreading'] = True
    if 'timeout_in_seconds' in valid:
        kwargs['timeout_in_seconds'] = timeout_secs
    if 'tournament_selection_n' in valid: kwargs['tournament_selection_n'] = 3
    if 'crossover_probability'  in valid: kwargs['crossover_probability']  = 0.9
    if 'mutation_weights' in valid:
        kwargs['mutation_weights'] = {
            'mutate_constant': 0.1, 'mutate_operator': 0.2,
            'add_node': 0.1, 'insert_node': 0.1, 'delete_node': 0.1,
            'simplify': 0.1, 'randomize': 0.05, 'do_nothing': 0.25,
        }
    if 'batching' in valid:
        kwargs['batching'] = True; kwargs['batch_size'] = 50
    return PySRRegressor(**kwargs)


def run_hypatia(X_train, y_train, X_ext, y_ext, seed=42,
                niterations=1000, timeout_secs=1100, populations=30):
    if not PYSR_AVAILABLE:
        return {'train_r2': None, 'extrap_r2': None, 'time_s': 0, 'error': 'pysr_not_installed'}
    try:
        model = make_pysr(seed=seed, niterations=niterations,
                          timeout_secs=timeout_secs, populations=populations)
    except Exception as e:
        return {'train_r2': None, 'extrap_r2': None, 'time_s': 0, 'error': str(e)}
    t0 = time.time()
    try:
        model.fit(X_train, y_train); elapsed = time.time() - t0
    except Exception as e:
        return {'train_r2': None, 'extrap_r2': None, 'time_s': time.time()-t0, 'error': str(e)}
    try:
        train_r2  = safe_r2(y_train, model.predict(X_train))
        extrap_r2 = safe_r2(y_ext, model.predict(X_ext)) if X_ext is not None else None
        best_expr = str(model.sympy())
    except Exception as e:
        train_r2 = extrap_r2 = None; best_expr = f'eval_error: {e}'
    return {'train_r2': train_r2, 'extrap_r2': extrap_r2,
            'time_s': elapsed, 'best_expression': best_expr}


