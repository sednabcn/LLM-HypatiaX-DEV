"""add_case_range_benchmark.py

Injects case-range slicing into every benchmark script in
hypatiax/experiments/benchmarks/ so CI mini-jobs only execute their assigned
slice of work.

What it does per file
─────────────────────
1. Inserts _apply_case_range() helper at the top of the module (after the
   last top-level import, detected via AST — not regex — to avoid injecting
   inside function bodies).

2. Finds the ONE top-level case-dispatch loop: the first for-loop whose
   iterable is a module-level name (EQUATIONS, PROBLEMS, SEEDS, etc.) or a
   range() call, at indentation level 0 inside the module body (not inside a
   function or class).  Wraps only that loop — inner loops are untouched.

3. Skips files that are already patched.

Fixes over the original version
────────────────────────────────
BUG 1 — indentation: _cases= line is now emitted at the same indent as the
         for-loop it replaces, not always at column 0.
BUG 2 — only the top-level dispatch loop is patched, not every for-loop.
BUG 3/4 — enumerate() and zip() / tuple-unpacking loops are recognised and
           skipped (they are never the right patch target).
BUG 5 — injection point is found via ast.parse so it always lands after the
         last top-level import statement, never inside a function body.
BUG 6 — os.getenv("CASE_RANGE_END", len(seq)) → str(len(seq)) so getenv
         never receives an int as the default.
BUG 7 — already_patched uses ast.parse to look for the function definition
         rather than a plain substring search.
"""

import ast
import re
import sys
from pathlib import Path

BENCH_DIR = Path("hypatiax/experiments/benchmarks")

# ── Injected helper (verbatim text inserted into each patched file) ────────────
INJECTION = '''\n# ── CASE RANGE INJECTION (auto-generated by add_case_range_benchmark.py) ──
def _apply_case_range(seq):
    """Return the slice of *seq* selected by CASE_RANGE_START/CASE_RANGE_END.

    Uses 1-based inclusive indexing to match CI --case-range N-M syntax.
    Returns seq unchanged when neither variable is set (local runs).
    """
    import os
    try:
        n = len(seq)
        start = max(0, int(os.getenv("CASE_RANGE_START", "1")) - 1)
        end   = min(n, int(os.getenv("CASE_RANGE_END",   str(n))))
        return seq[start:end]
    except Exception:
        return seq
# ────────────────────────────────────────────────────────────────────────────
'''


# ── Helpers ────────────────────────────────────────────────────────────────────

def _already_patched(source: str) -> bool:
    """Return True if the file already contains the _apply_case_range function.

    Uses AST so a comment or string containing the name does not cause a
    false positive.
    """
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return False
    return any(
        isinstance(node, ast.FunctionDef) and node.name == "_apply_case_range"
        for node in ast.walk(tree)
    )


def _injection_line(source: str) -> int:
    """Return the 0-based line index *after* the last top-level import.

    Uses ast.parse so imports inside function/class bodies are ignored.
    Falls back to line 0 if no imports are found.
    """
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return 0

    last_import_end = 0
    for node in ast.iter_child_nodes(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            # node.end_lineno is 1-based
            last_import_end = max(last_import_end, node.end_lineno)

    return last_import_end  # insert *after* this 1-based line → 0-based index


def _find_dispatch_loop(source: str) -> tuple[int, int, str] | None:
    """Find the first top-level for-loop that is a plausible case-dispatch loop.

    Returns (start_line_0based, end_line_0based_exclusive, indent_str) or None.

    "Top-level" means the for-node is a direct child of the module body (not
    inside a function or class).  Loops whose iterable is a call expression
    (enumerate, zip, reversed, …) are skipped because they are never the right
    target — the dispatch loop should iterate a plain list/range.
    """
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return None

    lines = source.splitlines()

    for node in ast.iter_child_nodes(tree):
        if not isinstance(node, ast.For):
            continue

        # Skip loops with tuple targets (for a, b in ...) — not dispatch loops
        if isinstance(node.target, ast.Tuple):
            continue

        # Skip loops whose iterable is a function call (enumerate, zip, …)
        # UNLESS it is range() which is a valid dispatch iterable
        iter_ = node.iter
        if isinstance(iter_, ast.Call):
            func = iter_.func
            func_name = (
                func.id if isinstance(func, ast.Name) else
                func.attr if isinstance(func, ast.Attribute) else ""
            )
            if func_name != "range":
                continue

        # Determine indentation from the source line
        line_idx  = node.lineno - 1          # 0-based
        line_text = lines[line_idx]
        indent    = len(line_text) - len(line_text.lstrip())
        indent_str = line_text[:indent]

        # end_lineno is the last line of the for-block (inclusive, 1-based)
        end_idx = node.end_lineno  # 0-based exclusive = end_lineno

        return line_idx, end_idx, indent_str

    return None


def _patch_source(source: str, path: Path) -> str | None:
    """Return patched source, or None if no change was needed / possible."""

    if _already_patched(source):
        print(f"  ✓ skip  {path.name}  (already patched)")
        return None

    # 1. Find injection point and insert helper
    inject_after = _injection_line(source)   # 1-based line number
    lines = source.splitlines(keepends=True)

    # Insert INJECTION block after line inject_after (1-based)
    lines.insert(inject_after, INJECTION)
    patched = "".join(lines)

    # 2. Re-parse patched source to find the dispatch loop (line numbers shifted)
    loop_info = _find_dispatch_loop(patched)
    if loop_info is None:
        print(f"  • skip  {path.name}  (no suitable top-level for-loop found)")
        return patched if INJECTION in patched else None

    loop_start, _loop_end, indent = loop_info
    loop_lines  = patched.splitlines(keepends=True)
    original_for = loop_lines[loop_start].rstrip("\n")

    # Extract the iterable expression from the for-statement
    # Handles: "for VAR in EXPR:" where EXPR may be a name or range(...)
    m = re.match(
        r"^(\s*)for\s+(\w+)\s+in\s+(.+?)\s*:\s*$",
        original_for,
    )
    if not m:
        print(f"  • skip  {path.name}  (could not parse for-loop: {original_for!r})")
        return patched if INJECTION in patched else None

    indent_str, loop_var, iterable = m.group(1), m.group(2), m.group(3)

    # Wrap the iterable with _apply_case_range
    new_assign = f"{indent_str}_cases = _apply_case_range({iterable})\n"
    new_for    = f"{indent_str}for {loop_var} in _cases:\n"

    loop_lines[loop_start] = new_assign + new_for
    patched = "".join(loop_lines)

    return patched


# ── Main ───────────────────────────────────────────────────────────────────────

def patch_file(path: Path, *, dry_run: bool = False) -> bool:
    """Patch *path* in place.  Returns True if the file was modified."""
    source = path.read_text(encoding="utf-8")

    try:
        new_source = _patch_source(source, path)
    except Exception as exc:
        print(f"  ✗ error {path.name}: {exc}")
        return False

    if new_source is None or new_source == source:
        return False

    # Validate the patched source parses correctly
    try:
        ast.parse(new_source)
    except SyntaxError as exc:
        print(f"  ✗ PATCH PRODUCED INVALID SYNTAX in {path.name}: {exc}")
        print("    File NOT written — please patch manually.")
        return False

    if dry_run:
        print(f"  ~ dry   {path.name}  (would patch)")
        return True

    path.write_text(new_source, encoding="utf-8")
    print(f"  ✅ patched {path.name}")
    return True


def main(argv: list[str] | None = None) -> None:
    import argparse

    parser = argparse.ArgumentParser(
        description="Inject _apply_case_range into benchmark scripts."
    )
    parser.add_argument(
        "--bench-dir", default=str(BENCH_DIR),
        help="Directory containing benchmark scripts (default: %(default)s)",
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Print what would be patched without writing any files.",
    )
    args = parser.parse_args(argv)

    bench = Path(args.bench_dir)
    if not bench.exists():
        print(f"✗ Benchmark directory not found: {bench}")
        sys.exit(1)

    files = sorted(f for f in bench.glob("*.py") if not f.name.startswith("_"))
    if not files:
        print(f"✗ No benchmark scripts found in {bench}")
        sys.exit(1)

    mode = "DRY-RUN" if args.dry_run else "PATCH"
    print(f"[{mode}] {len(files)} scripts in {bench}/\n")

    patched = sum(patch_file(f, dry_run=args.dry_run) for f in files)

    print(f"\n{'Would patch' if args.dry_run else 'Patched'}: {patched} / {len(files)} files")


if __name__ == "__main__":
    main()
